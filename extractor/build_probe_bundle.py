#!/usr/bin/env python3
"""Bundle plan.py + emit.py + probe.py into one dependency-free file: dist/office_probe.py.
A compute site then needs only `scp dist/office_probe.py plan.yaml user@site:` — no pip, no git."""
import os, re
here = os.path.dirname(os.path.abspath(__file__)); pkg = os.path.join(here, "office_extract")
parts = []
for name in ("plan", "emit", "probe"):
    src = open(os.path.join(pkg, name + ".py"), encoding="utf-8").read()
    src = re.sub(r"^from \.(plan|emit|probe) import .*$", "", src, flags=re.M)          # intra-package imports become same-file
    src = re.sub(r'^if __name__ == "__main__":\n    sys\.exit\(main\(\)\)\n?', "", src, flags=re.M)
    src = src.replace("def main(", f"def main_{name}(")
    parts.append(f"# ======== office_extract/{name}.py ========\n{src}")
out = os.path.join(os.path.dirname(here), "dist", "office_probe.py")
os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, "w", encoding="utf-8") as f:
    f.write("#!/usr/bin/env python3\n# office_probe.py — single-file bundle (plan + emit + probe). Generated by extractor/build_probe_bundle.py; do not edit.\n")
    f.write("from __future__ import annotations\n")
    f.write("\n".join(p.replace("from __future__ import annotations\n", "") for p in parts))
    f.write('\n\nif __name__ == "__main__":\n    import sys as _s\n    _s.exit(main_probe())\n')
print("wrote", out)
